lines.append('本文件收录微商城在售商品信息，包含商品名称、价格、库存、销量与所属分类。'
             '客服在回答商品咨询（如"有什么零食推荐""XX商品多少钱"）时，应优先参考本文件。\n')

for cid in sorted(groups):
    cname = groups[cid][0]['cname']
    main = MAIN.get(cid, '其他')
    lines.append(f'## {main} - {cname}\n')
    lines.append(CAT_DESC.get(cid, '') + '\n')
    lines.append('在售商品列表：\n')
    for r in groups[cid]:
        lines.append(
            f'- 【编号{r["id"]}】{r["name"]}，售价{r["price"]}元，库存{r["stock"]}件，已售{r["sales"]}件。'
        )
    lines.append('')

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines))

print(f'goods.md 生成完成：{len(rows)} 个商品，{len(groups)} 个子分类')
