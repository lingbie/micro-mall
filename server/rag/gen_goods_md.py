rows = []
with open(RAW, encoding='utf-8-sig') as f:
    for line in f:
        line = line.strip()
        if not line:
            continue
        parts = line.split('\t')
        if len(parts) < 7:
            continue
        rows.append({
            'id': int(parts[0]),
            'name': parts[1],
            'price': parts[2],
            'stock': parts[3],
            'sales': parts[4],
            'cid': int(parts[5]),
            'cname': parts[6],
        })

# 按子分类分组
groups = {}
for r in rows:
    groups.setdefault(r['cid'], []).append(r)

os.makedirs(os.path.dirname(OUT), exist_ok=True)
lines = []
